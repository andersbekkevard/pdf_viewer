"""Generate small synthetic PDFs that each isolate one feature known to stress a viewer.

    uv run bench/corpus/synth/generate.py                 # all generators
    uv run bench/corpus/synth/generate.py --list
    uv run bench/corpus/synth/generate.py --only rotate encrypt --force

Files go to $PDFV_CORPUS_DIR/incoming/synth/ (default
~/.local/share/pdf_viewer/corpus/incoming/synth/) as <generator>__<variant>.pdf.
Each file is written under a .part name and renamed; only then is its row
(filename, generated:<generator>, license) appended to _files.tsv, because ingest
may read the directory concurrently. Existing files are skipped unless --force.
See bench/corpus/sources/adversarial.md for what each generator covers.
"""

from __future__ import annotations

import argparse
import os
import shutil
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from registry import GENERATORS  # noqa: E402
import gen_raw, gen_damage, gen_tex, gen_rl, gen_browser, gen_overlay  # noqa: E402,F401

LICENSE = "CC0-1.0 (generated by bench/corpus/synth)"
LICENSE_FONTS = "generated by bench/corpus/synth; embeds subsets of macOS system fonts (local test use only)"


def corpus_dir() -> Path:
    return Path(os.environ.get("PDFV_CORPUS_DIR", Path.home() / ".local/share/pdf_viewer/corpus"))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--only", nargs="*", help="generator names to run")
    ap.add_argument("--out", type=Path, help="output dir (default incoming/synth)")
    ap.add_argument("--force", action="store_true", help="regenerate files that exist")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()

    if a.list:
        for name, g in GENERATORS.items():
            print(f"{name:20} {g.doc}")
        return 0
    out = a.out or corpus_dir() / "incoming" / "synth"
    out.mkdir(parents=True, exist_ok=True)
    tsv = out / "_files.tsv"
    listed = {l.split("\t", 1)[0] for l in tsv.read_text().splitlines()} if tsv.exists() else set()
    names = a.only or list(GENERATORS)
    failed = []
    for name in names:
        g = GENERATORS[name]
        if not a.force and g.variants and all(
                (out / f"{name}__{v}.pdf").exists() for v in g.variants):
            print(f"{name}: up to date")
            continue
        t0 = time.time()
        with tempfile.TemporaryDirectory(prefix=f"synth-{name}-") as tmp:
            try:
                files = g.fn(Path(tmp))
            except Exception as e:  # keep going; report at the end
                print(f"{name}: FAILED {type(e).__name__}: {e}", file=sys.stderr)
                failed.append(name)
                continue
            for variant, data in files.items():
                fname = f"{name}__{variant}.pdf"
                dest = out / fname
                if dest.exists() and not a.force:
                    continue
                part = out / (fname + ".part")
                if isinstance(data, Path):
                    shutil.copyfile(data, part)
                else:
                    part.write_bytes(data)
                os.replace(part, dest)
                if fname not in listed:
                    with open(tsv, "a") as f:
                        f.write(f"{fname}\tgenerated:{name}\t"
                                f"{LICENSE_FONTS if g.system_fonts else LICENSE}\n")
                    listed.add(fname)
        print(f"{name}: {len(files)} files in {time.time() - t0:.1f} s")
    if failed:
        print("failed:", " ".join(failed), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
